/**
 * Generates the Uplift wordmark as static vector paths.
 *
 * The wordmark is the lowercase word "uplift" set in Inter Tight ExtraBold
 * (SIL Open Font License) with the dot of the "i" replaced by a larger,
 * lifted, colored dot. Extracting outlines at build time means the mark
 * renders identically on iOS, Android and web without depending on font
 * loading, and can be scaled or recolored freely.
 *
 *   node scripts/build-wordmark.mjs
 *
 * Output: src/components/brand/wordmark.generated.ts (committed).
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const opentype = require('opentype.js');

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const fontPath = path.join(root, 'node_modules/@expo-google-fonts/inter-tight/800ExtraBold/InterTight_800ExtraBold.ttf');
const fontBuffer = fs.readFileSync(fontPath);
const font = opentype.parse(fontBuffer.buffer.slice(fontBuffer.byteOffset, fontBuffer.byteOffset + fontBuffer.byteLength));

const SIZE = 100;
const TRACKING = -0.03 * SIZE;
const BASELINE = 100;
const scale = SIZE / font.unitsPerEm;

const letters = ['u', 'p', 'l', 'ı', 'f', 't'];
let x = 0;
const commands = [];
let stem = null;
let box = { x1: Infinity, y1: Infinity, x2: -Infinity, y2: -Infinity };

letters.forEach((char, index) => {
  const glyph = font.charToGlyph(char);
  const glyphPath = glyph.getPath(x, BASELINE, SIZE);
  commands.push(glyphPath.toPathData(2));
  const b = glyphPath.getBoundingBox();
  if (char === 'ı') stem = b;
  box = { x1: Math.min(box.x1, b.x1), y1: Math.min(box.y1, b.y1), x2: Math.max(box.x2, b.x2), y2: Math.max(box.y2, b.y2) };
  const next = letters[index + 1];
  const kerning = next ? font.getKerningValue(glyph, font.charToGlyph(next)) * scale : 0;
  x += glyph.advanceWidth * scale + TRACKING + kerning;
});

// Calibrate against the font's own dotted "i", then lift and enlarge the dot.
const dotted = font.charToGlyph('i').getPath(0, BASELINE, SIZE).getBoundingBox();
const stemWidth = stem.x2 - stem.x1;
const radius = +(stemWidth * 0.66).toFixed(2);
const normalCenterY = dotted.y1 + stemWidth / 2;
const lift = SIZE * 0.1;
const dot = {
  cx: +((stem.x1 + stem.x2) / 2).toFixed(2),
  cy: +(normalCenterY - lift).toFixed(2),
  r: radius,
};

const pad = 2;
const top = Math.min(box.y1, dot.cy - dot.r) - pad;
const bottom = box.y2 + pad;
const left = box.x1 - pad;
const right = box.x2 + pad;
const viewBox = [left, top, right - left, bottom - top].map((n) => +n.toFixed(2));

const out = `// GENERATED by scripts/build-wordmark.mjs — do not edit by hand.
// Outlines: Inter Tight ExtraBold, SIL Open Font License 1.1.

export const WORDMARK = {
  viewBox: '${viewBox.join(' ')}',
  width: ${viewBox[2]},
  height: ${viewBox[3]},
  /** Baseline position from the top of the view box, for aligning with text. */
  baseline: ${+(BASELINE - top).toFixed(2)},
  letters: '${commands.join(' ')}',
  dot: { cx: ${dot.cx}, cy: ${dot.cy}, r: ${dot.r} },
} as const;
`;

const target = path.join(root, 'src/components/brand/wordmark.generated.ts');
fs.writeFileSync(target, out);
console.log(`Wrote ${path.relative(root, target)} (viewBox ${viewBox.join(' ')}, dot ${JSON.stringify(dot)})`);
